<?php
namespace Model;

/**
 * First-run installation helpers used by Controller_Setup.
 *
 * The game is considered installed once fuel/app/config/db.php exists and the
 * configured database contains the `user` table.
 */
class Setup
{
	/**
	 * Session settings applied to every connection. The game was written against
	 * MySQL's permissive SQL mode, so strict defaults of MySQL 8/9 are relaxed.
	 */
	const SESSION_COMMAND = "SET SESSION sql_mode = 'NO_ENGINE_SUBSTITUTION'";

	public static function config_path(): string
	{
		return APPPATH . 'config' . DIRECTORY_SEPARATOR . 'db.php';
	}

	public static function schema_path(): string
	{
		return APPPATH . 'db.sql';
	}

	public static function has_db_config(): bool
	{
		return is_file(static::config_path());
	}

	/**
	 * Whether the web installer still needs to run. Database errors propagate so
	 * an outage is reported as such instead of sending visitors to /setup.
	 */
	public static function needs_setup(): bool
	{
		if (!static::has_db_config()) {
			return true;
		}

		return count(\DB::query("SHOW TABLES LIKE 'user'", \DB::SELECT)->execute()) === 0;
	}

	/**
	 * Validate the database form fields and normalise them.
	 *
	 * @return array{host:string,port:int,name:string,user:string,password:string}
	 * @throws \InvalidArgumentException
	 */
	public static function validate_db_input(array $input): array
	{
		$db = array(
			'host'     => trim((string) ($input['host'] ?? '')),
			'port'     => trim((string) ($input['port'] ?? '3306')),
			'name'     => trim((string) ($input['name'] ?? '')),
			'user'     => trim((string) ($input['user'] ?? '')),
			'password' => (string) ($input['password'] ?? ''),
		);

		if (!preg_match('/^[A-Za-z0-9._\-]+$|^\[[0-9A-Fa-f:.]+\]$/', $db['host'])) {
			throw new \InvalidArgumentException('Database host may only contain letters, digits, dots, dashes and underscores.');
		}
		if (!ctype_digit($db['port']) || (int) $db['port'] < 1 || (int) $db['port'] > 65535) {
			throw new \InvalidArgumentException('Database port must be a number between 1 and 65535.');
		}
		if (!preg_match('/^[A-Za-z0-9_\-$]{1,64}$/', $db['name'])) {
			throw new \InvalidArgumentException('Database name may only contain letters, digits, dashes, underscores and $.');
		}
		if ($db['user'] === '' || strlen($db['user']) > 255) {
			throw new \InvalidArgumentException('Database user is required.');
		}

		$db['port'] = (int) $db['port'];

		return $db;
	}

	public static function dsn(array $db): string
	{
		return sprintf('mysql:host=%s;port=%d;dbname=%s;charset=utf8mb4', $db['host'], $db['port'], $db['name']);
	}

	/**
	 * Build the Fuel database config array for the given credentials.
	 */
	public static function db_config(array $db): array
	{
		return array(
			'default' => array(
				'type' => 'pdo',
				'connection' => array(
					'dsn'      => static::dsn($db),
					'username' => $db['user'],
					'password' => $db['password'],
				),
				'charset' => 'utf8mb4',
				'command' => static::SESSION_COMMAND,
			),
		);
	}

	/**
	 * Write fuel/app/config/db.php. Values are exported with var_export so user
	 * input can never break out of the generated PHP.
	 */
	public static function write_db_config(array $db): void
	{
		$php = "<?php\n"
			. "// Generated by the Secret Republic setup wizard on " . gmdate('Y-m-d H:i:s') . " UTC.\n"
			. "// Delete this file (and empty the database) to run /setup again.\n"
			. 'return ' . var_export(static::db_config($db), true) . ";\n";

		if (@file_put_contents(static::config_path(), $php, LOCK_EX) === false) {
			throw new \RuntimeException('Could not write ' . static::config_path() . '. Make sure the web server can write to fuel/app/config/.');
		}
	}

	/**
	 * Open a PDO connection from a Fuel "connection" config block.
	 */
	public static function connect(array $connection): \PDO
	{
		$pdo = new \PDO($connection['dsn'], $connection['username'] ?? null, $connection['password'] ?? null, array(
			\PDO::ATTR_ERRMODE => \PDO::ERRMODE_EXCEPTION,
			\PDO::ATTR_TIMEOUT => 5,
		));
		$pdo->exec(static::SESSION_COMMAND);

		return $pdo;
	}

	/**
	 * Read the connection block of the existing fuel/app/config/db.php.
	 */
	public static function existing_connection(): array
	{
		$config = include static::config_path();

		return $config['default']['connection'] ?? array();
	}

	public static function schema_installed(\PDO $pdo): bool
	{
		return $pdo->query("SHOW TABLES LIKE 'user'")->fetchColumn() !== false;
	}

	/**
	 * Create all tables and seed data from fuel/app/db.sql.
	 *
	 * @return int number of statements executed
	 */
	public static function import_schema(\PDO $pdo): int
	{
		$statements = static::split_sql((string) file_get_contents(static::schema_path()));
		foreach ($statements as $statement) {
			$pdo->exec($statement);
		}

		return count($statements);
	}

	/**
	 * Split an SQL dump into individual statements.
	 *
	 * Understands quoted strings ('...', "...", `...`) with backslash escapes,
	 * "--" / "#" line comments and C-style block comments, so semicolons inside
	 * mission texts or comments never split a statement. MySQL executable
	 * comments (/*! ... *\/) are preserved.
	 *
	 * @return string[]
	 */
	public static function split_sql(string $sql): array
	{
		$statements = array();
		$current = '';
		$length = strlen($sql);
		$quote = null;

		for ($i = 0; $i < $length; $i++) {
			$char = $sql[$i];
			$next = $i + 1 < $length ? $sql[$i + 1] : '';

			if ($quote !== null) {
				$current .= $char;
				if ($char === '\\' && $quote !== '`') {
					$current .= $next;
					$i++;
				} elseif ($char === $quote) {
					if ($next === $quote) {
						$current .= $next;
						$i++;
					} else {
						$quote = null;
					}
				}
				continue;
			}

			if ($char === "'" || $char === '"' || $char === '`') {
				$quote = $char;
				$current .= $char;
				continue;
			}

			$dash_comment = $char === '-' && $next === '-' && ($i + 2 >= $length || ctype_space($sql[$i + 2]));
			if ($dash_comment || $char === '#') {
				$end = strpos($sql, "\n", $i);
				$i = $end === false ? $length : $end;
				$current .= "\n";
				continue;
			}

			if ($char === '/' && $next === '*') {
				$end = strpos($sql, '*/', $i + 2);
				$end = $end === false ? $length : $end + 2;
				if ($i + 2 < $length && $sql[$i + 2] === '!') {
					$current .= substr($sql, $i, $end - $i);
				} else {
					$current .= ' ';
				}
				$i = $end - 1;
				continue;
			}

			if ($char === ';') {
				if (trim($current) !== '') {
					$statements[] = trim($current);
				}
				$current = '';
				continue;
			}

			$current .= $char;
		}

		if (trim($current) !== '') {
			$statements[] = trim($current);
		}

		return $statements;
	}
}
